#!/usr/bin/env bash
#
# Сводит папку прогона в одну таблицу: что слал генератор, что доехало,
# и во что это обошлось узлу.
#
#   ./summary.sh results/20260812-1754-s2-ingest
#
# Колонки:
#   point    имя точки замера (ступень темпа, число читателей, число лендов)
#   sent     сколько операций отправил генератор
#   recv     сколько наблюдений записали читатели
#   p50…max  задержка «записал → увидел», мс
#   cpu%     средняя загрузка ядра узла процессом базы за точку
#   rss      пик резидентной памяти базы, МБ
#   wrMB     записано на диск узла за точку, МБ (весь диск, не только база)
#
# recv меньше sent — это не обязательно потери: читатель опрашивает значение
# раз в миллисекунду, и несколько быстрых перезаписей подряд он видит как одну.
# Разрыв растёт вместе с темпом — это ожидаемо и само по себе не признак беды.

set -euo pipefail

dir="${1:-}"
[ -d "$dir" ] || { echo "Укажи папку прогона: ./summary.sh results/<дата>-<сценарий>" >&2; exit 1; }

printf '%-14s %8s %8s %6s %6s %6s %6s %7s %6s %7s\n' \
	point sent recv p50 p95 p99 max 'cpu%' rss wrMB

for log in "$dir"/*.log; do

	[ -e "$log" ] || continue

	point=$( basename "$log" .log )
	csv="$dir/$point.metrics.csv"

	# Строка итогов генератора идёт последней и начинается с усечённой ссылки
	# на ленд. Строку ALL (она есть только в многолендовом прогоне) берём в
	# приоритет: там уже сведены все ленды точки.
	read -r sent recv p50 p95 p99 max <<-EOF
		$( awk '
			/^ALL/ { s=$2; r=$3; a=$4; b=$5; c=$6; d=$7 }
			/^[A-Za-z0-9_]+…/ && s=="" { s=$2; r=$3; a=$4; b=$5; c=$6; d=$7 }
			END { print s, r, a, b, c, d }
		' "$log" 2>/dev/null )
	EOF

	cpu='-'; rss='-'; wr='-'

	if [ -s "$csv" ]; then
		read -r cpu rss wr <<-EOF
			$( awk -F, '
				NR == 2 { t0 = $1; cpu0 = $2 + $3; wr0 = $8 }
				NR > 1 {
					t1 = $1; cpu1 = $2 + $3; wr1 = $8
					if( $4 > rss ) rss = $4
				}
				END {
					dt = t1 - t0
					if( dt <= 0 ) { print "-", rss, "-"; exit }
					printf "%.1f %d %.1f\n", 100 * ( cpu1 - cpu0 ) / dt, rss, wr1 - wr0
				}
			' "$csv" 2>/dev/null )
		EOF
	fi

	printf '%-14s %8s %8s %6s %6s %6s %6s %7s %6s %7s\n' \
		"$point" "${sent:--}" "${recv:--}" "${p50:--}" "${p95:--}" "${p99:--}" "${max:--}" \
		"$cpu" "$rss" "$wr"

done

echo
echo "Стенд:"
sed -n 's/^/  /p' "$dir/manifest.txt" 2>/dev/null
